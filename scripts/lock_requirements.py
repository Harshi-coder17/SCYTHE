"""Resolve Linux locks with pip-tools and hash releases using official PyPI metadata.

Run in the pinned Python 3.11 build container with pip-tools==7.6.2 installed.
Fetching published SHA-256 digests avoids downloading every platform's wheel.
Installation still verifies the downloaded distribution against these digests.
"""
import concurrent.futures
import json
from pathlib import Path
import re
import subprocess
import tempfile
from urllib.request import urlopen


ROOT = Path(__file__).resolve().parents[1] / "containers"
SOURCES = ("backend/requirements.in", "backend/requirements.runner.in", "sandbox/docker/requirements.in")
PIN = re.compile(r"^([A-Za-z0-9_.-]+)(?:\[[^]]+\])?==([^\s;]+)$")


def release_hashes(pin):
    match = PIN.fullmatch(pin)
    if not match:
        raise ValueError(f"Expected an exact resolved pin: {pin}")
    package, version = match.groups()
    with urlopen(f"https://pypi.org/pypi/{package}/{version}/json", timeout=60) as response:
        metadata = json.load(response)
    hashes = sorted({item["digests"]["sha256"] for item in metadata["urls"]})
    if not hashes or any(not re.fullmatch(r"[0-9a-f]{64}", value) for value in hashes):
        raise ValueError(f"Missing or invalid release hashes: {pin}")
    return pin, hashes


def main():
    for source in SOURCES:
        with tempfile.TemporaryDirectory() as directory:
            resolved = Path(directory) / "resolved.txt"
            subprocess.run([
                "pip-compile", "--quiet", "--upgrade", "--strip-extras",
                "--index-url", "https://pypi.org/simple", str(ROOT / source),
                "--output-file", str(resolved),
            ], check=True)
            lines = resolved.read_text().splitlines()
            pins = [line.strip() for line in lines if line and not line.startswith(("#", " ", "--"))]
            with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
                hashes = dict(executor.map(release_hashes, pins))
            output = ["# Generated by scripts/lock_requirements.py on Linux Python 3.11.",
                      "# Resolved with pip-tools==7.6.2; hashes from official PyPI release metadata.",
                      "--index-url https://pypi.org/simple", ""]
            for pin in pins:
                output.append(pin + " \\")
                values = hashes[pin]
                output.extend("    --hash=sha256:" + value + (" \\" if index < len(values) - 1 else "")
                              for index, value in enumerate(values))
            destination = (ROOT / source).with_suffix(".txt")
            destination.write_text("\n".join(output) + "\n")
            print(f"Locked {source}: {len(pins)} packages", flush=True)


if __name__ == "__main__":
    main()
